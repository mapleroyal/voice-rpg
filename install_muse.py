#!/usr/bin/env python3
"""Register a thin Muse skill pointing to this checkout's dependency-free CLI."""
import argparse
import ast
import json
import os
from pathlib import Path
import shlex
import sys
import tempfile

from voice_rpg.contracts import VERSION

PROJECT = Path(__file__).resolve().parent
SKILL_NAME = "voice_rpg"
MARKER = "Generated by voice-rpg/install_muse.py"


def _write_atomic(path, text, mode=0o644):
    fd, temporary = tempfile.mkstemp(prefix="." + path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(text)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def install(project=PROJECT, skills_dir=None, data_dir=None):
    project = Path(project).expanduser().resolve()
    skills_dir = Path(skills_dir).expanduser().absolute() if skills_dir is not None else Path.home() / "workspace" / "custom-skills"
    destination = skills_dir / SKILL_NAME
    for relative in ("voice_rpg/cli.py", "voice_rpg/contracts.py", "skills/voice-rpg/SKILL.md"):
        if not (project / relative).is_file():
            raise ValueError("Incomplete Voice RPG checkout: " + str(project / relative))
    if destination.is_symlink() or (destination.exists() and not destination.is_dir()):
        raise ValueError("Refusing to replace a non-directory skill: " + str(destination))
    managed = ("skill.yaml", "SKILL.md", "rpg")
    owned = False
    for name in managed:
        path = destination / name
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise ValueError("Refusing to replace an unrelated skill file: " + str(path))
        if path.exists():
            if not any(MARKER in line for line in path.read_text(encoding="utf-8").splitlines()[:2]):
                raise ValueError("Refusing to replace an unrelated skill file: " + str(path))
            owned = True
    if destination.exists() and any(destination.iterdir()) and not owned:
        raise ValueError("Refusing to replace an unrelated skill: " + str(destination))
    launcher = destination.resolve() / "rpg"
    if data_dir is None and launcher.is_file():
        # Read the one stored binding without executing installed code.
        bindings = [ast.literal_eval(node.value) for node in ast.parse(launcher.read_text(encoding="utf-8")).body
                    if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == "DATA_DIR"
                                                           for target in node.targets)]
        if len(bindings) != 1 or not isinstance(bindings[0], str) or not Path(bindings[0]).is_absolute():
            raise ValueError("Existing launcher has no valid data binding; supply --data-dir explicitly.")
        data_dir = bindings[0]
    data_dir = Path(data_dir).expanduser().resolve() if data_dir is not None else Path.home() / "workspace" / "voice-rpg-data"
    destination.mkdir(parents=True, exist_ok=True)
    command = shlex.quote(str(launcher))
    wrapper = f'''#!/usr/bin/env python3
# {MARKER}
import sys
DATA_DIR = {str(data_dir)!r}
sys.path.insert(0, {str(project)!r})
from voice_rpg.cli import main
raise SystemExit(main(["--data-dir", DATA_DIR, *sys.argv[1:]]))
'''
    skill = f'''<!-- {MARKER} -->
# Voice RPG

CLI: `{command}` (invoke directly).

## Start
Run `resume` for saved context and the canonical narrator guide.

## API
Run `schema` to discover commands; `schema COMMAND` gives the input contract when needed. Gameplay commands take one JSON object on stdin. Results are `{{"ok":true,"result":...}}`; failures are `{{"ok":false,"error":...}}` with a nonzero exit code.
'''
    metadata = "# " + MARKER + "\n" + "\n".join(
        key + ": " + json.dumps(value) for key, value in {
            "name": SKILL_NAME,
            "title": "Voice RPG",
            "description": "Play or resume the user's persistent voice RPG.",
            "category": "Media",
            "include_in_prompt": True,
        }.items()) + "\n"
    # Publish the discovery manifest last, after its entrypoint and executable exist.
    _write_atomic(launcher, wrapper, 0o755)
    _write_atomic(destination / "SKILL.md", skill)
    _write_atomic(destination / "skill.yaml", metadata)
    return {"registered": True, "version": VERSION, "skill": str(destination.resolve()),
            "command": str(launcher), "data_dir": str(data_dir)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skills-dir", type=Path, help="Muse custom-skills directory (default: ~/workspace/custom-skills)")
    parser.add_argument("--data-dir", type=Path, help="Persistent collection directory (retains an installed binding; new default: ~/workspace/voice-rpg-data)")
    args = parser.parse_args(argv)
    try:
        if sys.version_info < (3, 12):
            raise ValueError("Use Python 3.12 or newer.")
        print(json.dumps(install(skills_dir=args.skills_dir, data_dir=args.data_dir)))
        return 0
    except (OSError, UnicodeError, ValueError, SyntaxError) as exc:
        print("Muse installation failed: " + str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
